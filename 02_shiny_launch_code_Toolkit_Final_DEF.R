## =========================================================
## 6. Verify that Cloudflare Analytics was inserted
## =========================================================

# Read the generated index.html into R.
index_html <- paste(
  readLines(
    file.path(repo_dir, "docs", "index.html"),
    warn = FALSE
  ),
  collapse = "\n"
)

# Confirm that the Cloudflare beacon is present.
#
# Expected result:
# [1] TRUE
grepl(
  "static.cloudflareinsights.com/beacon.min.js",
  index_html,
  fixed = TRUE
)



## =========================================================
## 7. Start a local web server for testing
## =========================================================

# Serve the generated docs/ folder locally so that the website
# can be tested before publishing it.
#
# The R console remains occupied until the server is stopped.
#
# Use the PUBLIC GitHub Pages URL, rather than localhost,
# when checking whether Cloudflare Analytics is collecting data.
httpuv::runStaticServer(
  file.path(repo_dir, "docs")
)

